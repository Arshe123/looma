// Stage 4/5: production UI, isolated settings and clipboard sink.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const directory = fs.mkdtempSync(path.join(os.homedir(), '.hermes/cache/scratch/looma-chunked-menus-'))
app.setPath('userData', path.join(directory, 'profile'))
const wait = (ms = 150) => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1100, height: 850, show: false, webPreferences: { backgroundThrottling: false } })
  const run = source => win.webContents.executeJavaScript(source)
  const errors = []
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message) })
  const until = async (source, label) => { for (let i=0;i<120;i++) { if (await run(source)) return; await wait(50) } throw new Error(`Timeout: ${label}`) }
  const focus = async () => {
    for (let i=0;i<30;i++) { await run('cm().focus()'); await wait(50); if (await run('document.hasFocus() && cm().hasFocus')) return }
    throw new Error('native focus unavailable')
  }
  const fixture = async source => { await run(`setFixture(${JSON.stringify(source)})`); await wait(700); await run('start(0)'); await focus(); await wait() }
  const key = async (keyCode, modifiers=[]) => { await focus(); for (const type of ['keyDown','keyUp']) win.webContents.sendInputEvent({type,keyCode,modifiers}); await wait(200) }
  const click = async selector => {
    const point=await run(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:r.left+r.width/2,y:r.top+r.height/2}})()`)
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
    await wait(150)
    for(const type of ['mousePressed','mouseReleased']) await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type,button:'left',clickCount:1,...point})
    await wait(250)
  }
  const context = async (offset, selector) => {
    await focus()
    const point=await run(selector ? `(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:(r.left+r.right)/2,y:(r.top+r.bottom)/2}})()` : `(()=>{const r=cm().coordsAtPos(${offset});return{x:r.left+1,y:(r.top+r.bottom)/2}})()`)
    for(const type of ['mousePressed','mouseReleased']) await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type,button:'right',clickCount:1,...point})
    await until('!!document.querySelector("[data-looma-editor-context-menu]:not([hidden])")','native context menu')
    await run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  }
  try {
    await win.loadURL('http://127.0.0.1:5189/src/renderer/components/editor/test/chunked-editor.browser.html')
    await until('window.ready?.() && !!cm()', 'production editor')
    await run('document.fonts.ready'); win.webContents.debugger.attach('1.3')
    await win.webContents.debugger.sendCommand('Emulation.setFocusEmulationEnabled',{enabled:true})
    await win.webContents.debugger.sendCommand('Page.bringToFront')
    await focus()
    await run('(async()=>{window.settings=(await import("/src/renderer/stores/settings.ts")).useSettingsStore();window.copied=[];Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:async text=>copied.push(text),readText:async()=>"粘贴文本"}})})()')
    await fixture('开始\n\n结束'); await run('select(3)'); await focus()
    await until('!!document.querySelector("[data-looma-continuous-menu-plus]:not([hidden])")', 'blank-line quick insert button')
    const geometry=await run('(()=>{const p=document.querySelector("[data-looma-continuous-menu-plus]").getBoundingClientRect();const n=[...cm().dom.querySelectorAll(".cm-lineNumbers .cm-gutterElement")].find(e=>e.textContent==="2");const r=n.getBoundingClientRect();return {dx:(p.left+p.right-r.left-r.right)/2,dy:(p.top+p.bottom-r.top-r.bottom)/2,number:getComputedStyle(n).visibility}})()')
    assert.ok(Math.abs(geometry.dx)<1 && Math.abs(geometry.dy)<1, 'plus overlays the actual gutter anchor')
    assert.equal(geometry.number,'hidden')
    await click('[data-looma-continuous-menu-plus]')
    assert.ok(await run('(()=>{const p=document.querySelector(".looma-continuous-menu-panel").getBoundingClientRect();const b=document.querySelector("[data-looma-continuous-menu-plus]").getBoundingClientRect();return Math.abs(p.left-Math.max(8,b.left))<1 && p.top>=b.bottom})()'),'pointer-opened panel follows the gutter button rather than jumping to body text')
    assert.equal(await run('document.querySelector(".looma-continuous-menu-panel [data-action=image]").disabled'),false,'production image insertion is available in the quick menu')
    fs.writeFileSync(path.join(directory,'quick-menu.png'),(await win.webContents.capturePage()).toPNG())
    await click('.looma-continuous-menu-panel [data-action="h2"]')
    assert.equal(await run('model().content'),'开始\n## \n结束')
    await key('z',['meta']); assert.equal(await run('model().content'),'开始\n\n结束')
    console.log('PASS native gutter +, configured quick menu action and canonical undo')

    for(const [action,keyCode,modifiers,marker] of [['bold','b',['meta'],'**'],['italic','i',['meta'],'*'],['strike','s',['meta','shift'],'~~'],['inlineCode','e',['meta'],'`'],['highlight','l',['meta'],'==']]) {
      await fixture('前 正文 后'); await run('select(2,4)'); await key(keyCode,modifiers)
      assert.equal(await run('model().content'),`前 ${marker}正文${marker} 后`,action)
      await key(keyCode,modifiers); assert.equal(await run('model().content'),'前 正文 后',`${action} reverses`)
      await fixture(''); await key(keyCode,modifiers)
      assert.equal(await run('model().selection.head'),marker.length,`${action} empty caret inside markers`)
      await win.webContents.debugger.sendCommand('Input.insertText',{text:'新'})
      await wait(200)
      assert.equal(await run('model().content'),`${marker}新${marker}`,`${action} actual input stays inside empty pair`)
      await key('z',['meta']); await key('z',['meta']); assert.equal(await run('model().content'),'')
    }
    console.log('PASS all five format shortcuts, empty native carets/input, reversible toggles and shared undo')

    await fixture('标题')
    for(const level of [6,5,4,3,2,1]) { await key('=', ['meta']); assert.equal(await run('model().content'),'#'.repeat(level)+' 标题') }
    const h1Revision=await run('model().revision'); await key('=', ['meta']); assert.equal(await run('model().revision'),h1Revision)
    for(const level of [2,3,4,5,6,0]) { await key('-', ['meta']); assert.equal(await run('model().content'),level?'#'.repeat(level)+' 标题':'标题') }
    await fixture('正文'); await run('select(0,2);settings.settings.editor.shortcuts.bold.enabled=false'); await key('b',['meta'])
    assert.equal(await run('model().content'),'正文','disabled native default cannot bypass settings')
    await run('settings.settings.editor.shortcuts.bold.enabled=true;settings.settings.editor.shortcuts.bold.key="K"')
    await key('b',['meta']); assert.equal(await run('model().content'),'正文')
    await key('k',['meta']); assert.equal(await run('model().content'),'**正文**')
    await key('z',['meta']); await run('settings.settings.editor.shortcuts.bold.key="B"')
    await run('window.originalMenu=[...settings.inlineMenuItems];settings.settings.inlineMenu.items=["h3","table"]')
    await fixture('正文'); await key('1',['meta']); assert.equal(await run('model().content'),'### 正文')
    await fixture(''); await key('2',['meta'])
    await until('document.querySelectorAll(".looma-continuous-menu-panel .table-size-picker__cell").length===60','configured shared table slot picker')
    await click('.looma-continuous-menu-panel .table-size-picker__cell[data-rows="2"][data-columns="3"]')
    assert.equal(await run('document.querySelector(".looma-continuous-table-row").dataset.tableColumns'),'3')
    assert.equal(await run('document.querySelectorAll(".looma-continuous-table-row").length'),2)
    await key('z',['meta']); assert.equal(await run('model().content'),'')
    await run('settings.settings.inlineMenu.items=originalMenu')
    console.log('PASS complete heading chain/boundaries, custom/disabled bindings, configured slots and real table picker')

    const table='| A | B |\n| --- | ---: |\n| one | two |'
    const tableActions=['rowBefore','rowAfter','columnBefore','columnAfter','rowUp','rowDown','columnLeft','columnRight','deleteRow','deleteColumn']
    for(const action of tableActions) {
      await fixture(table)
      const caret=action==='rowDown'?table.indexOf('A'):action==='columnRight'||action==='alignRight'?table.indexOf('one'):table.indexOf('two')
      await run(`select(${caret+1})`); await focus()
      await until('!!document.querySelector(".looma-continuous-menu-root .table-toolbar:not([hidden])")','shared table toolbar')
      const before=await run('model().revision')
      try { await context(caret+1) } catch(error) {
        console.error('TABLE_CONTEXT_DIAGNOSTIC',action,await run('JSON.stringify({source:model().content,selection:model().selection,menuHidden:document.querySelector(".looma-continuous-menu-panel")?.hidden,scroll:cm().scrollDOM.scrollTop})'))
        throw error
      }
      const renderedActions=await run('[...document.querySelectorAll(".looma-continuous-menu-panel [data-action]")].map(el=>el.dataset.action)')
      assert.deepEqual(renderedActions.filter(id=>tableActions.includes(id)),tableActions)
      if(action==='rowBefore') fs.writeFileSync(path.join(directory,'table-menu.png'),(await win.webContents.capturePage()).toPNG())
      await click(`.looma-continuous-menu-panel [data-action="${action}"]`)
      assert.notEqual(await run('model().content'),table,`${action} actual button changes source`)
      assert.equal(await run('model().revision'),before+1,`${action} is one canonical edit`)
      await key('z',['meta']); assert.equal(await run('model().content'),table,`${action} exact shared undo`)
    }
    console.log('PASS every table toolbar action, alignment/header invariants and exact single-step undo')
    await fixture(table); await run(`select(${table.indexOf('one')+1})`); await focus()
    await until('!!document.querySelector(".looma-continuous-menu-root .table-toolbar:not([hidden])")','shared toolbar for copy and resize')
    await click('.looma-continuous-menu-root .table-toolbar [aria-label="复制表格"]')
    assert.equal(await run('copied.at(-1)'),table,'shared toolbar copies exact source table')
    const toolbarBox=await run('(()=>{const r=document.querySelector(".looma-continuous-menu-root .table-toolbar").getBoundingClientRect();return {width:r.width,height:r.height}})()')
    await click('.looma-continuous-menu-root .table-toolbar [aria-label="调整表格大小"]')
    await until('!!document.querySelector(".looma-continuous-menu-root .table-toolbar .table-size-picker")','shared resize picker')
    assert.deepEqual(await run('(()=>{const r=document.querySelector(".looma-continuous-menu-root .table-toolbar").getBoundingClientRect();return {width:r.width,height:r.height}})()'),toolbarBox,'resize picker overlays without expanding toolbar')
    await click('.looma-continuous-menu-root .table-toolbar [data-rows="3"][data-columns="3"]')
    assert.equal(await run('document.querySelectorAll(".looma-continuous-table-row").length'),3)
    assert.equal(await run('document.querySelector(".looma-continuous-table-row").dataset.tableColumns'),'3')
    await key('z',['meta']); assert.equal(await run('model().content'),table)
    await click('.looma-continuous-menu-root .table-toolbar [aria-label="删除表格"]')
    assert.equal(await run('model().content'),'')
    await key('z',['meta']); assert.equal(await run('model().content'),table)
    console.log('PASS shared table toolbar copy, floating resize picker, resize/delete and canonical undo')

    const formatted='前 **正文** 后'
    await fixture(formatted); await run('select(2,8)'); await context(0)
    assert.deepEqual(await run('model().selection'),{anchor:2,head:8})
    await click('.looma-continuous-menu-panel [data-action="copy-source"]')
    assert.equal(await run('copied[copied.length-1]'),'**正文**')
    assert.equal(await run('model().content'),formatted)
    await context(0)
    assert.deepEqual(await run('[...document.querySelectorAll(".looma-continuous-menu-panel [data-action]")].map(el=>el.dataset.action).filter(id=>["cut","delete","selectAll"].includes(id))'),[],'context menu has no extra mutation actions')
    await key('Escape'); await key('Backspace')
    assert.equal(await run('model().content'),'前  后')
    await key('z',['meta']); assert.equal(await run('model().content'),formatted)
    await context(0); await click('.looma-continuous-menu-panel [data-action="paste"]')
    assert.equal(await run('model().content'),'前 粘贴文本 后')
    await key('z',['meta'])
    await fixture('前 [**引用**](other.md#L7 "标题") 后')
    await context(5); await click('.looma-continuous-menu-panel [data-action="copy-source"]')
    assert.equal(await run('copied[copied.length-1]'),'[**引用**](other.md#L7 "标题")')
    const image='![图](assets/a.png "标题"){width=60%}'
    await fixture(image); await context(0,'.looma-continuous-image')
    await click('.looma-continuous-menu-panel [data-action="copy-source"]')
    assert.equal(await run('copied[copied.length-1]'),image,'image context source keeps title and width')
    await context(0,'.looma-continuous-image')
    assert.deepEqual(await run('model().selection'),{anchor:0,head:image.length},'image context preserves a complete source selection')
    await key('Escape'); await key('Backspace')
    assert.equal(await run('model().content'),'')
    await key('z',['meta']); assert.equal(await run('model().content'),image)
    console.log('PASS native context selection preservation, isolated copy/cut/paste/source/link actions and undo')

    await fixture('开始\n\n结束'); await run('select(3)'); await focus()
    for(const width of [1500,1100,600,360]) {
      win.setSize(1600,850)
      await run(`document.getElementById("app").style.width="${width}px"`); await wait(300); await focus()
      await until('!!document.querySelector("[data-looma-continuous-menu-plus]:not([hidden])")','resized gutter plus')
      const drift=await run('(()=>{const p=document.querySelector("[data-looma-continuous-menu-plus]").getBoundingClientRect();const r=[...cm().dom.querySelectorAll(".cm-lineNumbers .cm-gutterElement")].find(e=>e.textContent==="2").getBoundingClientRect();return Math.abs((p.left+p.right-r.left-r.right)/2)})()')
      assert.ok(drift<1,`gutter alignment after outer width ${width}`)
      await click('[data-looma-continuous-menu-plus]')
      await run('settings.settings.editor.showLineNumbers=!settings.settings.editor.showLineNumbers'); await wait(150)
      await key('Escape')
    }
    await run('settings.settings.editor.showLineNumbers=true;document.getElementById("app").style.width="1100px"')
    assert.equal(await run('model().content'),'开始\n\n结束')
    fs.writeFileSync(path.join(directory,'menus.png'),(await win.webContents.capturePage()).toPNG())
    console.log('PASS hidden numbers preserve gutter, wide/narrow pane geometry and display-only menu changes')
    await run('window.originalCm=cm;window.cm=()=>originalCm()?.constructor.findFromDOM(document.querySelector(".chunked-markdown-editor:not(.chunked-source-only) .cm-editor"));window.select=(anchor,head)=>pane(false).selectSource(anchor,head);void 0')
    await click('button[title="分割视图"]'); await until('document.querySelectorAll(".cm-editor").length===2','split native views')
    await run('select(3)'); await focus()
    await until('!!document.querySelector("[data-looma-continuous-menu-plus]:not([hidden])")','split rich gutter plus')
    await click('[data-looma-continuous-menu-plus]')
    await run('settings.settings.editor.richTextZoom=150'); await wait(350)
    assert.equal(await run('document.querySelector(".looma-continuous-menu-panel").hidden'),true,'zoom closes stale menu geometry')
    const divider=await run('(()=>{const r=document.querySelector(".cursor-col-resize").getBoundingClientRect();return{x:(r.left+r.right)/2,y:r.top+100}})()')
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,...divider})
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mouseMoved',button:'left',buttons:1,x:divider.x+150,y:divider.y})
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,x:divider.x+150,y:divider.y})
    await wait(350); await focus()
    await until('!!document.querySelector("[data-looma-continuous-menu-plus]:not([hidden])")','split drag gutter plus')
    const splitDrift=await run('(()=>{const p=document.querySelector("[data-looma-continuous-menu-plus]").getBoundingClientRect();const r=[...cm().dom.querySelectorAll(".cm-lineNumbers .cm-gutterElement")].find(e=>e.textContent==="2").getBoundingClientRect();return Math.abs((p.left+p.right-r.left-r.right)/2)})()')
    assert.ok(splitDrift<1)
    await click('button[title="预览模式"]'); await wait(250)
    await run('settings.settings.editor.richTextZoom=100')
    await run('setFixture("开始\\n\\n结束",true)'); await wait(350)
    assert.equal(await run('document.querySelectorAll(".looma-continuous-menu-anchor:not([hidden])").length'),0,'partial-load mode exposes no mutation toolbar')
    await run('props.isPartial=false'); await wait(350); await focus(); await run('select(3)')
    await run('enableCache()'); await wait(350); await run('hide()'); await wait(350)
    assert.equal(await run('document.querySelectorAll(".looma-continuous-menu-anchor:not([hidden])").length'),0,'deactivated note leaves no active overlay')
    await run('show()'); await until('!!cm()','cached editor activated'); await focus(); await run('select(3)'); await wait(250)
    assert.equal(await run('document.querySelectorAll(".looma-continuous-menu-root").length'),1,'activation does not duplicate global menu listeners/roots')
    console.log('PASS real split drag, reading zoom, partial loading and KeepAlive menu lifecycle')
    assert.deepEqual(errors,[])
    console.log('REPORT',directory)
    win.webContents.debugger.detach(); win.destroy(); app.exit(0)
  } catch(error) { console.error(error); console.error('Renderer errors:',errors); win.destroy(); app.exit(1) }
})
