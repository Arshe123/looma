// Start Vite test mode on 5189, then npx electron scripts/verify-note-relations.cjs.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync, writeFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const profile = mkdtempSync(join(tmpdir(), 'looma-note-relations-'))
app.setPath('userData', profile)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1400, height: 850, show: false, webPreferences: { backgroundThrottling: false } })
  const run = code => win.webContents.executeJavaScript(code).catch(error => { console.error('Renderer expression failed:', code); throw error })
  const until = async (code, label) => {
    for (let i = 0; i < 160; i++) { if (await run(code)) return; await wait(50) }
    throw new Error(`Timeout: ${label}`)
  }
  const errors = []
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) { errors.push(message); console.error('Renderer:', message) } })
  try {
    await win.loadURL('http://127.0.0.1:5189/scripts/test/note-relations.html')
    win.webContents.debugger.attach('1.3')
    await win.webContents.debugger.sendCommand('Emulation.setFocusEmulationEnabled', { enabled: true })
    await win.webContents.debugger.sendCommand('Page.bringToFront')
    for (const chunked of [false, true]) {
      await run(`state.chunked=${chunked}; workspace.activeAuxiliaryPanel=null`)
      await until('document.querySelector(".looma-note-relations")?.textContent === "引用了 2 篇 · 被引用 1 篇"', `counts ${chunked}`)
      await wait(500)
      const before = await run('snapshot()'), events = await run('JSON.stringify(calls)')
      const rect = await run(`(()=>{const button=document.querySelector('.looma-note-relations'),r=button.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
      await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mousePressed', ...rect, button: 'left', clickCount: 1 })
      await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseReleased', ...rect, button: 'left', clickCount: 1 })
      await until('!!document.querySelector(".knowledge-panel") && graphView.forWorkspace("fixture").selectedPath === "a.md"', 'graph opened at note')
      await until(`!!document.querySelector('[data-card-path="a.md"]')`, 'note information card')
      assert.deepEqual(await run('snapshot()'), before, 'click preserves source/document/history')
      assert.equal(await run('JSON.stringify(calls)'), events, 'shared index reused, no edit/save or repeated file reads')
      const copied = await run('copy()')
      assert.ok(copied.includes('当前笔记') && !copied.includes('被引用') && !copied.includes('预计阅读'), 'native copy excludes title UI')
      for (const theme of ['light', 'dark']) {
        await run(`document.documentElement.dataset.theme='${theme}'; document.querySelector('main > section').style.width='360px'`)
        await wait(150)
        const geometry = await run(`(()=>{const b=document.querySelector('.looma-note-relations'),m=b.closest('.looma-note-reading-time'),h=${chunked ? "cm().contentDOM.querySelector('.looma-continuous-h1')" : "editor().view.dom.querySelector('h1')"},r=b.getBoundingClientRect(),s=getComputedStyle(b),range=document.createRange(),walker=document.createTreeWalker(h,NodeFilter.SHOW_TEXT);let text;while(text=walker.nextNode())if(text.textContent.includes('当前笔记'))break;if(!text)throw new Error('title text missing');range.selectNodeContents(text);const pane=document.querySelector('main > section').getBoundingClientRect();return {below:r.top>=range.getBoundingClientRect().bottom,inside:r.left>=pane.left&&r.right<=pane.right,color:s.color,cursor:s.cursor}})()`)
        assert.equal(geometry.below, true, JSON.stringify(geometry))
        assert.equal(geometry.inside, true, JSON.stringify(geometry))
        assert.equal(geometry.cursor, 'pointer')
      }
      await run("document.querySelector('main > section').style.width='800px'")
      await wait(200)
      const screenshot = join(tmpdir(), `looma-note-relations-${chunked ? 'continuous' : 'tiptap'}.png`)
      writeFileSync(screenshot, (await win.webContents.capturePage()).toPNG())
      console.log('SCREENSHOT', screenshot)
      console.log(`PASS ${chunked ? 'continuous' : 'Tiptap'}: counts, real click, current graph card, no document/history/events pollution, narrow light/dark layout`)
    }
    await run(`changeDisk('b.md', '# 乙')`)
    await until('document.querySelector(".looma-note-relations")?.textContent === "引用了 2 篇 · 被引用 0 篇"', 'incoming count refreshes on filesystem changes')
    await run(`workspace.openedTextFileContents['a.md']={content:'# 当前笔记',isPartial:false,isLoading:false}`)
    await until('document.querySelector(".looma-note-relations")?.textContent === "引用了 0 篇 · 被引用 0 篇"', 'complete live draft updates outgoing count')
    await run('state.chunked=false; workspace.activeAuxiliaryPanel=null')
    await until('!!editor() && !!document.querySelector(".looma-note-relations")', 'Tiptap remounted')
    await wait(500)
    await run('document.querySelector(".looma-note-relations").focus()')
    assert.equal(await run('document.activeElement.matches(".looma-note-relations")'), true, 'keyboard target focused')
    await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', text: '\r', windowsVirtualKeyCode: 13 })
    await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })

    await until('workspace.activeAuxiliaryPanel === "graph"', 'keyboard opens graph')
    await run('state.external=true')
    await until('!!editor() && !document.querySelector(".looma-note-relations")', 'external note hides workspace-only counts')
    await run(`state.external=false;state.content=${JSON.stringify('# 第一个\n\n正文\n\n# 第二个')}`)
    await until('document.querySelectorAll(".looma-note-relations").length===1', 'single title relation summary')
    await run(`state.content=${JSON.stringify('正文\n\n## 小标题')}`)
    await until('!document.querySelector(".looma-note-relations")', 'no eligible title')
    assert.deepEqual(errors, [], 'renderer console errors')
    console.log('PASS keyboard, external isolation, one title only and no-title case')
  } finally { win.destroy(); rmSync(profile, { recursive: true, force: true }) }
}).then(() => app.quit()).catch(error => { console.error(error); app.exit(1) })
