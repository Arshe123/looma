// Isolated real CodeMirror → canonical rope → ordinary NoteRefPicker flow.
const { app, BrowserWindow } = require('electron')
console.log('references harness starting')
app.on('ready',()=>console.log('references Electron ready'))
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const directory = fs.mkdtempSync(path.join(os.homedir(), '.hermes/cache/scratch/looma-references-'))
app.setPath('userData', path.join(directory, 'profile'))
const wait = (ms = 100) => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  console.log('references creating hidden window')
  const win = new BrowserWindow({ width:1000,height:850,show:false,webPreferences:{backgroundThrottling:false} })
  console.log('references hidden window created')
  const errors=[]
  win.webContents.on('console-message',(_e,level,message)=>{if(level>=3)errors.push(message)})
  const run = code => win.webContents.executeJavaScript(code)
  const cdp = (name,params) => win.webContents.debugger.sendCommand(name,params)
  const poll = async expression => { for(let i=0;i<100;i++){if(await run(expression))return;await wait(50)}throw Error('等待失败：'+expression+' '+JSON.stringify(errors)) }
  const key = async (key,code=key) => {await cdp('Input.dispatchKeyEvent',{type:'keyDown',key,code});await cdp('Input.dispatchKeyEvent',{type:'keyUp',key,code})}
  try {
    await Promise.race([win.loadURL('http://127.0.0.1:5189/src/renderer/components/editor/test/continuous-references.browser.html'),wait(15000).then(()=>{throw Error('夹具加载超时 '+JSON.stringify(errors))})])
    win.webContents.debugger.attach('1.3')
    await cdp('Emulation.setFocusEmulationEnabled',{enabled:true})
    await poll('window.ready?.()');await run('install()');await wait(300)
    await cdp('Input.insertText',{text:'[['})
    await poll('!!snapshot().request && !!document.querySelector("input[placeholder^=搜索笔记]")')
    await poll('document.activeElement?.tagName==="INPUT"')
    assert.equal((await run('snapshot()')).source,'前文 ')
    await cdp('Input.insertText',{text:'目标 笔记'})
    await poll('document.querySelector("input[placeholder^=搜索笔记]")?.value==="目标 笔记" && [...document.querySelectorAll("button")].some(button=>button.textContent.includes("目标 笔记"))')
    await key('Enter')
    await poll('!snapshot().request')
    const selected=await run('snapshot()')
    assert.equal(selected.source,'前文 [](../docs/目标 笔记.md)')
    assert.equal(selected.selection,4)
    assert.deepEqual(selected.calls,['memory'])
    await cdp('Input.insertText',{text:'完整引用'})
    assert.equal((await run('snapshot()')).source,'前文 [完整引用](../docs/目标 笔记.md)')
    await run('undo()');await wait();await run('redo()');await wait()
    assert.equal((await run('snapshot()')).source,'前文 [完整引用](../docs/目标 笔记.md)')
    assert.equal(await run('document.querySelectorAll("#continuous .cm-editor").length'),1)
    const lifecycle=await run('lifecycle()')
    for(const result of lifecycle) assert.deepEqual(result,{flag:result.flag,rejected:true,unchanged:true,cancelled:true})
    await run(`(async()=>{controller.open(cm());await nextTick();await nextTick();window.oldHandlers=pickerHandlers();controller.cancel();await nextTick();controller.open(cm());await nextTick();await nextTick()})()`)
    const beforeLate=await run('snapshot()')
    await run('oldHandlers.onSelect(selectPayload)');await wait()
    assert.deepEqual(await run('snapshot()'),beforeLate,'old keyed picker select must not select a new request')
    await run('oldHandlers.onClose()');await wait()
    assert.deepEqual(await run('snapshot()'),beforeLate,'old keyed picker close must not cancel a new request')
    const closeRace=await run('(async()=>{const handlers=pickerHandlers();controller.cancel();controller.open(cm());handlers.onClose();await nextTick();await nextTick();return !!snapshot().request})()')
    assert.equal(closeRace,true,'close emitted before Vue rerender cannot cancel replacement pending request')
    await run('controller.cancel()');await wait()
    await run('(async()=>{controller.open(cm());fixture.active=false;await nextTick()})()')
    assert.equal(await run('snapshot().request'),null,'queued publication must recheck deactivation before showing picker')
    await run('fixture.active=true;controller.cancel()');await wait()
    const referenceSource='前 [**完整** *引用*](target.md#L12-15 "标题") [**相邻**](target.md) [网站](https://example.com "site") 后'
    const copied=await run(`renderRuns(${JSON.stringify(referenceSource)})`)
    assert.equal(copied.source,'[**完整** *引用*](target.md#L12-15 "标题")')
    await run('pm().commands.setTextSelection(pm().state.doc.content.size-1);cm().focus()');await wait(200)
    for(const theme of ['light','dark']){
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`);await wait(150)
      const actual=await run('linkStyles("#runs")'),ordinary=await run('linkStyles("#ordinary")')
      assert.equal(actual.filter(a=>a.icon).length,3,'one icon for each complete link')
      assert.equal(ordinary.filter(a=>a.icon).length,3,'ordinary oracle contains three links')
      assert.deepEqual(actual.map(({width,height,...value})=>value),ordinary.map(({width,height,...value})=>value),theme+' reference runs and computed styles match ordinary oracle')
    }
    await run('(async()=>{controller.open(cm());await nextTick();await nextTick();window.destroyRequest=snapshot().request;window.destroySource=model.content;mounted.$.appContext.app.unmount();await nextTick()})()')
    assert.equal(await run('controller.select(destroyRequest,selectPayload)'),false,'destroyed view rejects delayed selection')
    assert.equal(await run('model.content===destroySource'),true)
    assert.deepEqual(errors,[])
    console.log('PASS real [[ → shared NoteRefPicker search/Enter → relative Markdown template → label input → canonical rope undo/redo; lifecycle/stale events/destroy; full copy and standalone CM run styles versus ordinary Tiptap day/night (host link-plan wiring still required)')
    win.destroy();app.exit(0)
  } catch(error) { console.error(error);console.error(errors);try{console.log('STATE',await run('({snapshot:snapshot(),active:document.activeElement?.outerHTML,inputs:[...document.querySelectorAll("input")].map(i=>i.value)})'))}catch{};console.log('REPORT',directory);win.destroy();app.exit(1) }
})
