// Vite test mode on 5189; real Vue components/CSS with isolated memory data.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const profile = fs.mkdtempSync(path.join(process.env.TMPDIR, 'looma-message-dialog-'))
app.setPath('userData', profile)
app.setPath('sessionData', profile)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const watchdog = setTimeout(() => { console.error('FAIL message dialog timed out'); app.exit(1) }, 90000)

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1000, height: 750, webPreferences: { backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message) })
  const run = code => win.webContents.executeJavaScript(code)
  const until = async (expression, label) => {
    for (let i = 0; i < 100; i++) { if (await run(expression)) return; await wait(30) }
    throw new Error(`Timeout: ${label}`)
  }
  try {
    await win.loadURL('http://127.0.0.1:5189/scripts/test/message-dialog.html')
    win.webContents.debugger.attach('1.3')
    const cdp = (method, options) => win.webContents.debugger.sendCommand(method, options)
    await cdp('Emulation.setFocusEmulationEnabled', { enabled: true })
    await until('window.ready', 'fixture ready')
    const key = async (key, code, value, modifiers = 0) => {
      for (const type of ['keyDown', 'keyUp']) await cdp('Input.dispatchKeyEvent', { type, key, code, windowsVirtualKeyCode: value, modifiers })
    }
    const click = async selector => {
      const point = await run(`(() => { const r = document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect(); return { x: r.x+r.width/2, y: r.y+r.height/2 } })()`)
      await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...point, button: 'left', clickCount: 1 })
      await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', ...point, button: 'left', clickCount: 1 })
    }
    const focus = index => until(`document.activeElement?.dataset.messageDialogResponse === '${index}'`, `button ${index} focused`)
    const closed = () => until('!document.querySelector("[data-message-dialog]")', 'dialog closed')

    await run("document.querySelector('#opener').focus(); confirm({title:'确认删除？',message:'移入回收站',confirmText:'删除',danger:true});void 0")
    await focus(1)
    assert.equal(await run('document.querySelector("[data-message-dialog]").parentElement === document.body'), true, 'teleports outside clipped/transformed parent')
    await key('Enter', 'Enter', 13)
    await closed()
    assert.deepEqual(await run('results'), [false], 'Enter on initially focused cancel never deletes')
    assert.equal(await run('document.activeElement.id'), 'opener', 'returns focus to opener')
    console.log('PASS destructive default cancellation, Teleport and focus restoration')

    await run("show({type:'warning',title:'内容尚未保存',message:'保存？',buttons:['保存','不保存','取消'],defaultId:0,cancelId:2});void 0")
    await focus(0)
    await key('Tab', 'Tab', 9, 8)
    await focus(2)
    await key('Tab', 'Tab', 9)
    await focus(0)
    await run("document.querySelector('#opener').focus()")
    await focus(0)
    await click('[data-message-dialog-response="1"]')
    await closed()
    assert.deepEqual(await run('results.at(-1)'), { response: 1 }, 'middle button preserves response index')
    console.log('PASS three-button response, Tab/Shift+Tab trap and outside focus guard')

    await run("show({message:'第一条',buttons:['继续','取消'],cancelId:1});show({type:'info',message:'第二条'});void 0")
    await focus(1)
    const firstId = await run('dialogs.current.id')
    assert.equal(await run('document.querySelectorAll("[data-message-dialog]").length'), 1)
    await key('Escape', 'Escape', 27)
    await until('document.querySelector("[role=alertdialog]")?.textContent.includes("第二条")', 'second queued prompt')
    await run(`dialogs.respond(${firstId},0)`)
    assert.equal(await run('dialogs.current.options.message'), '第二条')
    await focus(0)
    await key('Enter', 'Enter', 13)
    await closed()
    assert.deepEqual(await run('results.slice(-2)'), [{ response: 1 }, { response: 0 }])
    console.log('PASS queued prompts, stale response guard, Escape and information acknowledgment')

    await run("template();void 0")
    await until('!!document.querySelector("#note-template-title")', 'underlying template mounted')
    await run("confirm({title:'删除模板？',message:'只取消这次删除',danger:true});void 0")
    await focus(1)
    await key('Escape', 'Escape', 27)
    await closed()
    assert.equal(await run('templateCloses'), 0, 'Escape does not close underlying modal')
    assert.equal(await run('!!document.querySelector("#note-template-title")'), true)
    await key('Escape', 'Escape', 27)
    await until('templateCloses===1', 'template closes after top dialog dismissed')
    console.log('PASS nested template modal receives no Escape through message dialog')

    await key('s', 'KeyS', 83, 4)
    assert.equal(await run('externalSaves'), 1, 'real external-document shortcut is enabled without a modal')
    await run('externalSaves=0;drop();void 0')
    await focus(0)
    await key('s', 'KeyS', 83, 4)
    assert.equal(await run('externalSaves'), 0, 'local editor alert blocks the earlier external save capture listener')
    assert.equal(await run('document.querySelector("[role=alertdialog] h2").textContent'), '无法插入该文件')
    assert.equal(await run('!!document.querySelector("[role=alertdialog] details")'), true)
    assert.equal(await run('!!document.querySelector("[role=alertdialog] b")'), false, 'technical detail is text, never HTML')
    await key('Escape', 'Escape', 27)
    await closed()
    console.log('PASS editor file error reuses shared view and safe collapsible technical details')

    await run('drop();void 0')
    await focus(0)
    await run("show({title:'后台警告',type:'warning',message:'只关闭最上层提示',buttons:['继续','取消'],cancelId:1});void 0")
    await until('document.activeElement?.closest("[role=alertdialog]")?.getAttribute("aria-label")==="后台警告"', 'topmost message owns focus')
    await key('Escape', 'Escape', 27)
    await until('document.querySelectorAll("[data-message-dialog]").length===1', 'underlying local alert remains')
    assert.equal(await run('document.querySelector("[role=alertdialog]").getAttribute("aria-label")'), '无法插入该文件')
    await key('Escape', 'Escape', 27)
    await closed()
    console.log('PASS overlapping local and global messages keep focus and Escape in the topmost dialog')

    win.setSize(360, 500)
    for (const palette of ['paper', 'graphite', 'ocean']) for (const theme of ['light', 'dark']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)};document.documentElement.dataset.palette=${JSON.stringify(palette)};document.documentElement.classList.toggle('dark',${theme === 'dark'});show({type:'info',title:'提示',message:${JSON.stringify('很长的中文路径和内容'.repeat(120))}});void 0`)
      await focus(0)
      const geometry = await run(`(() => { const el=document.querySelector('[role=alertdialog]'), r=el.getBoundingClientRect(); return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:innerWidth,height:innerHeight,scroll:el.scrollWidth<=el.clientWidth,bg:getComputedStyle(el).backgroundColor} })()`)
      assert.ok(geometry.left >= 0 && geometry.right <= geometry.width && geometry.top >= 0 && geometry.bottom <= geometry.height, 'long content stays within small viewport')
      assert.equal(geometry.scroll, true)
      assert.notEqual(geometry.bg, 'rgba(0, 0, 0, 0)')
      // Overlay pointer dismissal acknowledges single-button information dialogs.
      await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', x: 2, y: 2, button: 'left', clickCount: 1 })
      await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 2, y: 2, button: 'left', clickCount: 1 })
      await closed()
    }
    console.log('PASS three palettes × light/dark, narrow viewport, long messages and overlay dismissal')
    assert.deepEqual(errors, [], 'no renderer errors')
    win.webContents.debugger.detach()
    win.destroy()
    clearTimeout(watchdog)
    console.log('PASS shared message dialog Electron/CDP regression; isolated profile:', profile)
    app.exit(0)
  } catch (error) {
    console.error(error)
    clearTimeout(watchdog)
    win.destroy()
    app.exit(1)
  }
})
