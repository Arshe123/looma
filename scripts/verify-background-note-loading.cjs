// Vite test mode on 5189; memory documents and isolated profile only.
const {app,BrowserWindow}=require('electron')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {homedir}=require('node:os')
const root=fs.mkdtempSync(path.join(homedir(),'.hermes/cache/scratch/looma-background-note-'))
app.setPath('userData',path.join(root,'profile'))
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms))
app.whenReady().then(async()=>{
 const win=new BrowserWindow({width:1150,height:820,show:true,webPreferences:{backgroundThrottling:false}})
 const run=code=>win.webContents.executeJavaScript(code)
 const until=async(code,label)=>{for(let i=0;i<100;i++){if(await run(code))return;await wait(40)}throw new Error('Timeout: '+label)}
 const errors=[]
 win.webContents.on('console-message',(_event,level,message)=>{if(level>=3)errors.push(message.slice(0,300))})
 const watchdog=setTimeout(()=>{console.error('FAIL background loading stalled');win.destroy();app.exit(1)},60000)
 try{
  await win.loadURL('http://127.0.0.1:5189/src/renderer/components/editor/test/chunked-editor.browser.html')
  await until('window.ready?.() && !!cm()','editor mounted')
  await run('window.partialFrames=0;window.countFrame=()=>{partialFrames++;if(props.isPartial)requestAnimationFrame(countFrame)};requestAnimationFrame(countFrame);setFixture(("可连续阅读的正文 **加粗**。\\n\\n").repeat(18000),true)')
  await until('events.loads===1','remaining source starts automatically without click')
  assert.ok(await run('events.loadFrames[0]>=2'),'first screen must have a paint opportunity before background I/O')
  assert.equal(await run('cm().state.readOnly'),true)
  assert.match(await run('document.querySelector(".continuous-partial-state").textContent'),/后台加载/)
  assert.equal(await run('document.querySelector(".continuous-partial-state button")'),null,'no manual-load button while background request is running')
  const before=await run('(()=>{cm().scrollDOM.scrollTop=35;return {top:cm().scrollDOM.scrollTop,focus:cm().hasFocus,pending:events.pending,saves:events.saves.length}})()')
  await run('releaseLoad()')
  await until('!props.isPartial && !cm().state.readOnly','automatically becomes editable')
  assert.equal(await run('!!document.querySelector(".continuous-partial-state")'),false)
  assert.equal(await run('model().content===fullContent'),true)
  assert.equal(await run('cm().hasFocus'),before.focus,'background completion cannot steal focus')
  assert.ok(Math.abs(await run('cm().scrollDOM.scrollTop')-before.top)<2,'background completion preserves reading position')
  assert.equal(await run('events.pending'),before.pending)
  assert.equal(await run('events.saves.length'),before.saves,'background loading must not save')
  console.log('PASS first-paint deferred automatic loading, read-only protection, full completion without click/focus/scroll/save changes')

  await run('failLoad=true;setFixture(fullContent+"失败重试",true)')
  await until('events.loads===2','automatic second document load')
  await run('releaseLoad()')
  await until('document.body.textContent.includes("测试读取失败")','background error visible')
  await wait(200)
  assert.equal(await run('events.loads'),2,'failure cannot create an automatic retry loop')
  assert.equal(await run('cm().state.readOnly'),true)
  await run('failLoad=false;start(60)')
  await until('events.loads===3','explicit retry starts')
  await run('start(80)')
  assert.equal(await run('events.loads'),3,'repeated edit requests join one full read')
  await run('releaseLoad()')
  await until('!props.isPartial && !cm().state.readOnly','retry completes')
  assert.equal(await run('model().content===fullContent'),true)
  console.log('PASS visible background failure, no retry storm, shared explicit retry and safe editing after full read')

  await run('chunk().stopEditing();setFixture(fullContent+"取消",true)')
  await until('events.loads===4','background request before close')
  await run('hide();releaseLoad()')
  await wait(150)
  assert.equal(await run('props.isPartial'),true,'closed editor cancels remaining background work')
  await run('show()')
  await until('ready() && events.loads===5','reopening resumes pending source')
  await run('releaseLoad()')
  await until('!props.isPartial && !cm().state.readOnly','reopened editor ready')
  assert.equal(await run('model().content===fullContent'),true)
  assert.deepEqual(errors,[])
  console.log('PASS cancelled close cannot focus/update a stale editor; reopening resumes background load')
  await run('enableCache()');await until('ready() && !!cm()','cached editor mounted')
  await run('setFixture(fullContent+"切换标签",true)')
  await until('events.loads===6','background request before cached deactivation')
  await run('hide();releaseLoad()');await wait(150)
  assert.equal(await run('props.isPartial'),true,'deactivated cached editor cancels remaining work')
  await run('show()');await until('ready() && events.loads===7','cached activation resumes source loading')
  await run('releaseLoad()');await until('!props.isPartial && !cm().state.readOnly','cached editor becomes editable')
  assert.equal(await run('model().content===fullContent'),true)
  assert.deepEqual(errors,[])
  console.log('PASS real KeepAlive deactivation/activation cancels and resumes background completion')
  clearTimeout(watchdog);win.destroy();app.exit(0)
 }catch(error){console.error(error);console.error('Renderer errors:',errors);clearTimeout(watchdog);win.destroy();app.exit(1)}
})
