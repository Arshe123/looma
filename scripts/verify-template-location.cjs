// Requires Vite test mode on port 5191. All directories and writes are in memory.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const profile = mkdtempSync(join(tmpdir(), 'looma-location-'))
app.setPath('userData', profile)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show:false, width:1000, height:760, webPreferences:{backgroundThrottling:false} })
  const run = async code => { try { return await win.webContents.executeJavaScript(code) } catch (error) { console.error('Failed script:', code); throw error } }
  const wait = async condition => { for(let i=0;i<100;i++){if(await run(`Boolean(${condition})`)) return; await new Promise(r=>setTimeout(r,50))} throw new Error(condition) }
  const click = selector => run(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const trigger = '[aria-label="选择笔记新建位置"]'
  const choose = path => click(`[data-location-path="${path}"]`)
  try {
    await win.loadURL('http://127.0.0.1:5191/scripts/test/template-location.html')
    await wait('window.ready && document.querySelector("[data-template-card=test]")')
    assert.equal(await run(`[...document.querySelectorAll('button')].filter(e=>e.textContent.includes('管理模板')).length`),1)
    await click(trigger)
    await wait('document.querySelector("[data-location-path=\\\"项目/子目录\\\"]")')
    assert.equal(await run(`document.querySelector('[role=tree]').textContent.includes('笔记.md') || document.querySelector('[role=tree]').textContent.includes('.looma')`),false)
    await choose('项目/子目录')
    assert.ok(await run(`document.querySelector('${trigger}').textContent.includes('项目/子目录')`))
    await click('[data-template-card=blank]')
    assert.deepEqual(await run('JSON.parse(JSON.stringify(testState.blanks))'),['项目/子目录'])
    await run('reopen()'); await wait('document.querySelector("[data-template-card=test]")')
    await click(trigger); await wait('document.querySelector("[data-location-path=其他]")')
    await choose('其他'); await run('testState.pending=true')
    await click('[data-template-card=test]'); await wait('typeof window.finish === "function"')
    assert.equal(await run(`document.querySelector('${trigger}').disabled`),true)
    assert.deepEqual(await run('JSON.parse(JSON.stringify(testState.calls.at(-1)))'),{workspaceId:'固定工作空间',parentDirRelativePath:'其他',templateId:'test'})
    await run('finish()'); await wait('!document.querySelector("[role=dialog]")')
    await run('reopen()'); await wait('document.querySelector("[data-template-card=test]")')
    await click(trigger); await wait('document.querySelector("[role=tree]")')
    await run(`window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`)
    assert.equal(await run('!!document.querySelector("[role=tree]")'),false)
    assert.equal(await run('!!document.querySelector("[role=dialog]")'),true)
    await click(trigger); await wait('document.querySelector("[data-location-path=其他]")')
    await click('[aria-label="折叠项目"]')
    assert.equal(await run('!!document.querySelector("[data-location-path=\\\"项目/子目录\\\"]")'),false)
    await choose(''); assert.ok(await run(`document.querySelector('${trigger}').textContent.includes('工作空间根目录')`))
    await click(trigger); await run(`document.querySelector('h2').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`)
    assert.equal(await run('!!document.querySelector("[role=tree]")'),false)
    await run('testState.fail=true'); await click(trigger)
    await wait('document.querySelector("[role=tree]").textContent.includes("文件夹加载失败")')
    await run(`testState.fail=false; [...document.querySelectorAll('[role=tree] button')].find(e=>e.textContent.includes('重试')).click()`)
    await wait('document.querySelector("[data-location-path=其他]")')
    win.setSize(420,600)
    await wait('innerWidth === 420 && !document.querySelector("[role=tree]")')
    await click(trigger); await wait('document.querySelector("[role=tree]")')
    const bounds=await run(`(()=>{const r=document.querySelector('[role=tree]').getBoundingClientRect();return {left:r.left,right:r.right,bottom:r.bottom,width:innerWidth,height:innerHeight}})()`)
    assert.ok(bounds.left>=0 && bounds.right<=bounds.width && bounds.bottom<=bounds.height,JSON.stringify(bounds))
    console.log('PASS: nested directory selection, blank/custom destinations, captured workspace, pending lock, single manager, root selection, expand/collapse, Escape/outside close, error retry, narrow viewport')
    win.destroy(); rmSync(profile,{recursive:true,force:true}); app.exit(0)
  } catch(error){console.error(error);win.destroy();rmSync(profile,{recursive:true,force:true});app.exit(1)}
})
