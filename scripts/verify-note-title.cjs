// Start: npx vite --mode test --host 127.0.0.1 --port 5189 --strictPort
// Then: npx electron scripts/verify-note-title.cjs
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync, writeFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const profile = mkdtempSync(join(tmpdir(), 'looma-note-title-'))
app.setPath('userData', profile)
const wait = (ms=400) => new Promise(resolve=>setTimeout(resolve,ms))
app.whenReady().then(async()=>{
 const win=new BrowserWindow({width:1500,height:850,show:false,webPreferences:{backgroundThrottling:false}})
 const run=code=>win.webContents.executeJavaScript(code)
 // Allow the real component's 150ms local serialization gate to settle before an external replacement.
 const fixture=async(content,chunked=false,partial=false)=>{await wait(200);await run(`setFixture(${JSON.stringify(content)},${chunked},${partial})`);await wait()}
 const key=async(keyCode,modifiers=[])=>{win.webContents.sendInputEvent({type:'keyDown',keyCode,modifiers});win.webContents.sendInputEvent({type:'keyUp',keyCode,modifiers});await wait(100)}
 const errors=[]
 win.webContents.on('console-message',(_event,level,message)=>{if(level>=3) errors.push(message)})
 try {
  await win.loadURL('http://127.0.0.1:5189/scripts/test/note-title.html')
  for(let i=0;i<100;i++){if(await run('window.ready?.()')) break;await wait(100)}
  assert.ok(await run('ready()'),'real Tiptap mounted')
  win.webContents.debugger.attach('1.3')
  await win.webContents.debugger.sendCommand('DOM.enable')
  await win.webContents.debugger.sendCommand('CSS.enable')
  await run('document.fonts.ready');await wait()
  assert.deepEqual(await run('metadata()'),['预计阅读 1 分钟'])
  const baseline=await run('snapshot()'), initialEvents=await run('JSON.stringify(events)')
  await run('refreshMetadata()');await wait(1100)
  assert.deepEqual(await run('snapshot()'),baseline,'metadata not in document, serialization, copy or undo')
  assert.equal(await run('JSON.stringify(events)'),initialEvents,'metadata must not emit dirty/update/save')
  console.log('PASS nonpersisted decoration: Markdown/HTML/JSON/plain-copy/source-copy/history and save events')
  for(const chunked of [false,true]) {
   for(const [content,count] of [['# Title\n\n## Section',1],['# Title\n\nbody\n\n## Section',1],['# Title\n\n# Later',1],['\n\n# Title',1],['Setext\n======',1],['body\n\n# Later',0],['#\n\n# Later',0],['> # Nested',0],['```\n# Fake\n```',0],['- # Nested',0]]) {
    await fixture(content,chunked)
    assert.equal((await run('metadata()')).length,count,`eligibility ${chunked}: ${content}`)
   }
   await fixture('# 标题 Title\n\n## Section\n\n正文 body',chunked)
   let cases=0
   for(const font of ['simple','literary','handwritten']) for(const theme of ['light','dark']) for(const palette of ['paper','graphite','ocean']) for(const zoom of [75,100,200]) for(const width of [360,1400]) {
    await run(`appearance('${font}','${theme}','${palette}',${zoom},${width})`);await wait(20)
    const m=await run('measure()')
    assert.equal(m.border,'0px');assert.equal(parseFloat(m.font),30*zoom/100)
    assert.equal(m.weight,'550');assert.equal(m.marker,'"H1"');assert.equal(m.count,1)
    assert.ok(Math.abs(m.titleGap-10.944*zoom/100)<1,JSON.stringify(m))
    assert.ok(Math.abs(m.bodyGap-29.952*zoom/100)<1,JSON.stringify(m))
    assert.equal(m.align,0);assert.ok(m.overflow<=1,JSON.stringify(m));cases++
    if(theme==='light' && palette==='paper' && zoom===100 && width===1400) {
     await run('document.querySelector(".looma-note-body h1").scrollIntoView({block:"start"})');await wait(50)
     const {root}=await win.webContents.debugger.sendCommand('DOM.getDocument')
     const {nodeId}=await win.webContents.debugger.sendCommand('DOM.querySelector',{nodeId:root.nodeId,selector:'.looma-note-body h1'})
     const {fonts}=await win.webContents.debugger.sendCommand('CSS.getPlatformFontsForNode',{nodeId})
     assert.ok(fonts.some(font=>font.isCustomFont && font.glyphCount>0),'actual local title font')
     console.log('FONT',chunked?'chunked':'Tiptap',font,JSON.stringify(fonts))
    }
   }
   console.log(`PASS ${chunked?'chunked':'Tiptap'} appearance: ${cases} font/theme/palette/zoom/width cases`,JSON.stringify(await run('measure()')))
  }
  await run("appearance('handwritten','light','paper',100,1000)")
  // Force a title/H2 boundary at the real 64KiB split without a 64KiB heading.
  const cross='# Title'+ ' '.repeat(65536)+'\n\n## Section\n\nbody\n\n# Later'
  await fixture(cross,true,true)
  assert.deepEqual(await run('metadata()'),['阅读时间待全文加载'])
  assert.ok(await run('document.querySelectorAll(".markdown-render-chunk").length>1'))
  assert.ok(Math.abs((await run('measure()')).bodyGap-29.952)<1,'cross-chunk H2 margin')
  const loads=await run('events.loads')
  await run('props.isPartial=false');await wait()
  assert.deepEqual(await run('metadata()'),['预计阅读 1 分钟'])
  assert.equal(await run('events.loads'),loads,'completion does not request content')
  await fixture(cross+'\n\n'+'word '.repeat(401),true)
  assert.deepEqual(await run('metadata()'),['预计阅读 3 分钟'],'cached title changes for full document')
  console.log('PASS chunk boundary, pending→complete, appended whole-document count and no forced read')
  await fixture('# Title\n\nbody')
  await run('editor().commands.focus(6)');await wait(100);await key('Return')
  assert.equal(await run('editor().state.doc.childCount'),3,'Enter creates only a real paragraph')
  await key('Backspace')
  assert.equal(await run('editor().state.doc.childCount'),2,'Backspace crosses decoration')
  await run('editor().commands.focus(6)');await wait(100);await key('Right')
  assert.equal(await run('editor().state.selection.$head.parent.type.name'),'paragraph')
  await key('Left')
  assert.equal(await run('editor().state.selection.$head.parent.type.name'),'heading')
  await key('-', ['meta'])
  assert.equal((await run('metadata()')).length,0,'heading shortcut downgrade removes decoration immediately')
  await key('z',['meta'])
  assert.equal((await run('metadata()')).length,1,'undo restores')
  await key('z',['meta','shift'])
  assert.equal((await run('metadata()')).length,0,'redo removes')
  await fixture('# 标题\n\n正文')
  await run('editor().commands.focus(3)');await wait(100)
  await win.webContents.debugger.sendCommand('Input.imeSetComposition',{text:'中文输入',selectionStart:4,selectionEnd:4})
  await win.webContents.debugger.sendCommand('Input.insertText',{text:'中文输入'})
  await wait()
  assert.ok(await run('editor().state.doc.firstChild.textContent.includes("中文输入")'),'IME composition commits into heading')
  assert.equal((await run('metadata()')).length,1)
  const copied=await run(`(()=>{editor().commands.selectAll();const data=new DataTransfer();editor().view.dom.dispatchEvent(new ClipboardEvent('copy',{bubbles:true,cancelable:true,clipboardData:data}));return data.getData('text/plain')})()`)
  assert.ok(!copied.includes('预计阅读'));assert.ok(copied.includes('中文输入'))
  console.log('PASS real Electron Enter/Backspace/arrows/heading shortcut/undo/redo/CDP IME/native copy event')
  await fixture('# 标题\n\n'+Array.from({length:100},(_,i)=>`## Section ${i}\n\n这是正文 ${i}，用于验证滚动同步与行号。`).join('\n\n'))
  await run('document.querySelector("button[title=分割视图]").click()');await wait(700)
  assert.ok(await run('!!document.querySelector(".cm-editor")'),'actual split view')
  await run('document.querySelector(".cm-scroller").scrollTop=600');await wait()
  assert.ok(await run('document.querySelector(".tiptap-preview-container").scrollTop>100'),'source→rich scroll')
  await run('document.querySelector(".tiptap-preview-container").scrollTop=1400');await wait()
  assert.ok(await run('document.querySelector(".cm-scroller").scrollTop>650'),'rich→source scroll')
  const gutter=await run('document.querySelector(".tiptap").getBoundingClientRect().left')
  await run('settings.settings.editor.showLineNumbers=false');await wait()
  assert.equal(await run('document.querySelector(".tiptap").getBoundingClientRect().left'),gutter)
  assert.ok(await run('document.querySelectorAll(".looma-line-number[data-line]").length>100'))
  await run('jump(90)');await wait(800)
  assert.ok(await run('document.querySelector(".tiptap-preview-container").scrollTop>2000'))
  assert.equal(await run('document.querySelectorAll(".tiptap h1,.tiptap h2").length'),101)
  await run('document.querySelector("button[title=编辑模式]").click()');await wait()
  assert.equal((await run('metadata()')).length,0)
  await run('document.querySelector("button[title=预览模式]").click()');await wait(700)
  assert.equal((await run('metadata()')).length,1)
  console.log('PASS actual MarkdownEditor split, bidirectional scroll, line anchors/gutter, outline jump and source/preview mode switching')
  await fixture('# '+ '长标题自动换行'.repeat(12)+'\n\n## 正文')
  await run("appearance('handwritten','dark','paper',100,500)");await wait()
  assert.ok(await run('document.querySelector(".tiptap h1").getBoundingClientRect().height>60'))
  const image=await win.webContents.capturePage()
  const screenshot=join(tmpdir(),'looma-note-title-verification.png');writeFileSync(screenshot,image.toPNG())
  console.log('SCREENSHOT',screenshot)
  assert.deepEqual(errors,[],'renderer errors')
  console.log('PASS note title Electron verification')
  win.destroy();rmSync(profile,{recursive:true,force:true});app.exit(0)
 }catch(error){console.error(error);console.error('Renderer errors:',errors);win.destroy();rmSync(profile,{recursive:true,force:true});app.exit(1)}
})
